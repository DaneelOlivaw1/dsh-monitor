/** The name a derived supervisor gets for one target session. */
export function supervisorTitle(sessionId, title) {
  return `${SUPERVISOR_PREFIX}${(title ?? '').trim() === '' ? sessionId : title.trim()}`
}

/** The header button: derive a supervisor, or jump to the existing one. */
function DeriveSupervisorButton({ sessionId, useSessions, derive, focus, t }) {
  const isSupervisor = useSessions((state) => (state.byId[sessionId]?.title ?? '').startsWith(SUPERVISOR_PREFIX))
  const existingId = useSessions((state) => {
    const wanted = supervisorTitle(sessionId, state.byId[sessionId]?.title)
    const found = Object.values(state.byId ?? {}).find((session) => (session.title ?? '') === wanted)
    return found?.id
  })
  // A supervisor has no supervisor of its own: two would just talk past each other.
  if (isSupervisor === true) return null
  const jump = typeof existingId === 'string' && existingId !== ''
  const hint = t(jump ? 'hintJump' : 'hint')
  return jsx('button', {
    type: 'button',
    title: hint,
    'aria-label': hint,
    style: BUTTON_STYLE,
    onClick: () => (jump ? focus(existingId) : derive(sessionId)),
    children: t(jump ? 'jump' : 'label'),
  })
}

/** Whether the host currently draws the dark theme. */
function useDarkTheme() {
  // The theme attribute lands on <body>, not <html>; watch both so a toggle
  // repaints the diagram instead of leaving it in the previous scheme.
  const read = () => typeof document !== 'undefined' && (
    document.body?.hasAttribute('data-ds-dark-theme') === true
    || document.documentElement.hasAttribute('data-ds-dark-theme')
  )
  const [dark, setDark] = useState(read)
  useEffect(() => {
    if (typeof MutationObserver === 'undefined') return undefined
    const observer = new MutationObserver(() => setDark(read()))
    const options = { attributes: true, attributeFilter: ['data-ds-dark-theme'] }
    observer.observe(document.documentElement, options)
    if (document.body !== null) observer.observe(document.body, options)
    return () => observer.disconnect()
  }, [])
  return dark
}

/**
 * The loop document from the Host.
 *
 * One read per open and one per refresh: the document changes when a verdict
 * lands, which is minutes apart, so polling would spend requests to learn nothing.
 */
function useLoopData(sessionId) {
  const [state, setState] = useState({ status: 'loading', data: undefined, error: '' })
  const load = useCallback(() => {
    setState((previous) => ({ ...previous, status: previous.data === undefined ? 'loading' : 'refreshing' }))
    fetch(`/monitor/loop?session=${encodeURIComponent(sessionId)}`, { headers: { accept: 'application/json' } })
      .then(async (response) => {
        const body = await response.json()
        if (body.ok !== true) throw new Error(body.message ?? body.error ?? 'read-failed')
        setState({ status: 'ready', data: body, error: '' })
      })
      .catch((error) => setState((previous) => ({
        ...previous,
        status: 'error',
        error: error instanceof Error ? error.message : String(error),
      })))
  }, [sessionId])
  useEffect(() => { load() }, [load])
  return [state, load]
}

/**
 * The state graph, drawn by mermaid, in a viewport that starts on "the whole graph".
 *
 * The sidebar is narrow and a run is tall, so any scale legible on its own hides
 * most of the flow. The page therefore opens on the fit — every node at once,
 * whole labels, no clipping — and the reader zooms (buttons, ⌘/Ctrl+wheel) and
 * drags to walk the chain one position at a time. mermaid emits `width="100%"`,
 * which inside a flex column resolves to a zero-height strip, so the viewBox is
 * the source of truth and this component sets the pixel size.
 */
function LoopDiagram({ source, dark, t }) {
  const [svg, setSvg] = useState('')
  const [failed, setFailed] = useState('')
  const [natural, setNatural] = useState({ width: 0, height: 0 })
  const [viewport, setViewport] = useState({ width: 0, height: 0 })
  // `null` means "follow the fit": a resized sidebar re-fits without a click.
  const [scale, setScale] = useState(null)
  const holder = useRef(null)
  const applied = useRef(1)
  const pending = useRef(null)
  const drag = useRef(null)

  useEffect(() => {
    let alive = true
    const id = `monitor-loop-${Math.random().toString(36).slice(2, 10)}`
    setFailed('')
    mermaid.initialize({
      startOnLoad: false,
      securityLevel: 'strict',
      theme: dark ? 'dark' : 'default',
      // 11px and tight spacing: the same graph at 16px needs twice the room.
      fontFamily: 'inherit',
      themeVariables: { fontSize: '11px' },
      flowchart: {
        htmlLabels: false,
        curve: 'basis',
        useMaxWidth: false,
        wrappingWidth: 220,
        nodeSpacing: 12,
        rankSpacing: 16,
        padding: 4,
        diagramPadding: 2,
      },
    })
    mermaid.render(id, source)
      .then((result) => { if (alive) setSvg(result.svg) })
      .catch((error) => { if (alive) setFailed(error instanceof Error ? error.message : String(error)) })
    return () => { alive = false }
  }, [source, dark])

  // Natural size, read before any scaling: the viewBox is the drawing's truth.
  useEffect(() => {
    const element = holder.current?.querySelector('svg')
    const box = element?.viewBox?.baseVal
    if (box === undefined || box.width <= 0 || box.height <= 0) return
    element.style.maxWidth = 'none'
    element.style.display = 'block'
    element.style.margin = '0 auto'
    setNatural({ width: box.width, height: box.height })
  }, [svg])

  // The viewport is watched, not measured once: the sidebar is resizable.
  useEffect(() => {
    const element = holder.current
    if (element === null || element === undefined) return undefined
    // The 4px padding is inside clientWidth; the drawing must not use it, or it
    // always overflows by 8px and grows a scrollbar even when fitted.
    const read = () => setViewport({ width: Math.max(0, element.clientWidth - 8), height: Math.max(0, element.clientHeight - 8) })
    read()
    if (typeof ResizeObserver === 'undefined') return undefined
    const observer = new ResizeObserver(read)
    observer.observe(element)
    return () => observer.disconnect()
  }, [svg])

  const shown = scale === null ? initialScale(natural, viewport) : clampScale(scale)

  // One place turns scale into pixels; an anchor keeps the point under the
  // cursor still while the scale changes.
  useEffect(() => {
    const element = holder.current
    const element2 = element?.querySelector('svg')
    if (element === null || element === undefined || element2 === null || element2 === undefined) return
    if (natural.width <= 0 || natural.height <= 0) return
    applied.current = shown
    element2.setAttribute('width', String(Math.round(natural.width * shown)))
    element2.setAttribute('height', String(Math.round(natural.height * shown)))
    element2.style.maxWidth = 'none'
    const anchor = pending.current
    pending.current = null
    if (anchor === null || anchor.prev <= 0) return
    const moved = scrollAfterZoom({
      scrollLeft: element.scrollLeft,
      scrollTop: element.scrollTop,
      x: anchor.x,
      y: anchor.y,
      prev: anchor.prev,
      next: shown,
    })
    element.scrollLeft = moved.left
    element.scrollTop = moved.top
  }, [svg, natural, shown])

  /** Zoom around a point of the viewport (its centre by default). */
  const zoomTo = (next, atX, atY) => {
    const element = holder.current
    if (element === null || element === undefined) return
    const x = atX ?? element.clientWidth / 2
    const y = atY ?? element.clientHeight / 2
    pending.current = { x, y, prev: applied.current }
    setScale(clampScale(next))
  }

  // ⌘/Ctrl+wheel, the gesture a browser already trained: it must not fight the
  // page scroll, so a plain wheel is left alone.
  useEffect(() => {
    const element = holder.current
    if (element === null || element === undefined) return undefined
    const onWheel = (event) => {
      if (event.ctrlKey !== true && event.metaKey !== true) return
      event.preventDefault()
      const rect = element.getBoundingClientRect()
      const factor = event.deltaY < 0 ? ZOOM_STEP : 1 / ZOOM_STEP
      zoomTo(applied.current * factor, event.clientX - rect.left, event.clientY - rect.top)
    }
    element.addEventListener('wheel', onWheel, { passive: false })
    return () => element.removeEventListener('wheel', onWheel)
  }, [])

  const onPointerDown = (event) => {
    if (event.button !== 0) return
    const element = holder.current
    if (element === null || element === undefined) return
    drag.current = { x: event.clientX, y: event.clientY, left: element.scrollLeft, top: element.scrollTop }
    if (typeof element.setPointerCapture === 'function') element.setPointerCapture(event.pointerId)
    element.style.cursor = 'grabbing'
  }
  const onPointerMove = (event) => {
    const held = drag.current
    const element = holder.current
    if (held === null || held === undefined || element === null || element === undefined) return
    element.scrollLeft = held.left - (event.clientX - held.x)
    element.scrollTop = held.top - (event.clientY - held.y)
  }
  const endDrag = () => {
    drag.current = null
    if (holder.current !== null && holder.current !== undefined) holder.current.style.cursor = 'grab'
  }

  if (failed !== '') {
    return jsx('pre', {
      style: { margin: 0, overflowX: 'auto', fontSize: '11px', color: 'var(--dsw-alias-label-secondary)' },
      children: source,
    })
  }
  if (svg === '') {
    return jsx('div', { style: { fontSize: '11px', color: 'var(--dsw-alias-label-tertiary)' }, children: '…' })
  }

  const zoomButton = (label, onClick, title) => jsx('button', {
    type: 'button',
    title,
    'aria-label': title,
    style: { ...BUTTON_STYLE, height: '22px', padding: '0 6px', fontSize: '11px' },
    onClick,
    children: label,
  })

  return jsxs('div', { style: { minWidth: 0 }, children: [
    jsxs('div', {
      style: {
        display: 'flex',
        alignItems: 'center',
        gap: '4px',
        marginBottom: '4px',
        fontSize: '11px',
        color: 'var(--dsw-alias-label-tertiary)',
      },
      children: [
        zoomButton('−', () => zoomTo(applied.current / ZOOM_STEP), t('zoomOut')),
        jsx('span', {
          style: { minWidth: '36px', textAlign: 'center', fontVariantNumeric: 'tabular-nums' },
          children: `${Math.round(shown * 100)}%`,
        }),
        zoomButton('＋', () => zoomTo(applied.current * ZOOM_STEP), t('zoomIn')),
        zoomButton(t('fit'), () => setScale(null), t('fit')),
      ],
    }),
    jsx('div', {
      ref: holder,
      title: t('panHint'),
      onPointerDown,
      onPointerMove,
      onPointerUp: endDrag,
      onPointerCancel: endDrag,
      onDoubleClick: () => setScale(scale === null ? 1 : null),
      style: {
        overflow: 'auto',
        maxWidth: '100%',
        height: '60vh',
        minHeight: '240px',
        maxHeight: '640px',
        padding: '4px',
        border: '1px solid var(--dsw-alias-border-l2)',
        borderRadius: '6px',
        background: 'var(--dsw-alias-bg-layer-1)',
        cursor: 'grab',
        touchAction: 'none',
      },
      dangerouslySetInnerHTML: { __html: svg },
    }),
  ] })
}

